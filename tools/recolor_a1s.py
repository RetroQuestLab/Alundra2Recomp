def recolor(data: bytes, table: dict) -> bytes:
    assert data[:4] == b"A1SP", "pas un sprite .a1s"
    out = bytearray(data)
    n = struct.unpack_from("<H", out, 4)[0]
    off = 6
    for _ in range(n):
        w, h = struct.unpack_from("<HH", out, off)
        off += 8 + w * h * 4
    for i in range(6, off, 4):
        if out[i + 3] == 0:
            continue
        rgb = tuple(out[i:i + 3])
        if rgb in table:
            out[i:i + 3] = bytes(table[rgb])
    return bytes(out)


